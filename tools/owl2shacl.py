#!/usr/bin/env python3
"""Generate basic OWL consistency shapes (SHACL) for an ontology.

Only constraints whose violation makes the data contradict the ontology under OWL (open world) semantics are
generated:

- object properties take resources (IRIs or blank nodes) and datatype properties take literals;
- literals of a datatype property with an XSD (or other datatype) range have a compatible datatype;
- maximum cardinalities from owl:maxCardinality / owl:cardinality restrictions and owl:FunctionalProperty.

Minimum cardinalities and class membership implied by rdfs:domain / rdfs:range are not checked: under OWL they are
inferences, not contradictions, and the JSON-LD exchange encoding rarely types the nodes involved.

Numeric datatypes (xsd:decimal, double, float and the integer types) are treated as one family, because JSON-LD maps
JSON numbers to xsd:double or xsd:integer whatever the declared range. Strings accept rdf:langString, and dates accept
xsd:date, xsd:dateTime and xsd:dateTimeStamp.

Usage: owl2shacl.py ONTOLOGY.ttl OUTPUT.ttl
"""
import sys
from pathlib import Path

from rdflib import BNode, Graph, Literal, Namespace, URIRef
from rdflib.collection import Collection
from rdflib.namespace import OWL, RDF, RDFS, XSD

SH = Namespace('http://www.w3.org/ns/shacl#')

NUMERIC = [XSD.decimal, XSD.double, XSD.float, XSD.integer]
NUMERIC_RANGES = {XSD.decimal, XSD.double, XSD.float, XSD.integer, XSD.int, XSD.long, XSD.short,
                  XSD.nonNegativeInteger, XSD.positiveInteger, XSD.nonPositiveInteger, XSD.negativeInteger}
STRING = [XSD.string, RDF.langString]
DATES = [XSD.date, XSD.dateTime, XSD.dateTimeStamp]


def accepted_datatypes(rng: URIRef) -> list[URIRef] | None:
    if rng in NUMERIC_RANGES:
        return NUMERIC
    if rng == XSD.string:
        return STRING
    if rng in (XSD.date, XSD.dateTime, XSD.dateTimeStamp):
        return DATES
    if rng in (RDFS.Literal, None):
        return None
    if str(rng).startswith(str(XSD)) or (rng, RDF.type, RDFS.Datatype) in ONT:
        return [rng]
    return None


def add_list(g: Graph, items: list) -> BNode:
    head = BNode()
    Collection(g, head, items)
    return head


def generate(ont_file: Path) -> Graph:
    global ONT
    ONT = Graph()
    ONT.parse(ont_file)
    ont_iri = next(ONT.subjects(RDF.type, OWL.Ontology), None)
    base = (str(ont_iri).rstrip('/#') if ont_iri else ont_file.stem) + '.owl-shapes#'

    out = Graph()
    out.bind('sh', SH)
    out.bind('xsd', XSD)
    shapes_ont = URIRef(base[:-1])
    out.add((shapes_ont, RDF.type, OWL.Ontology))
    out.add((shapes_ont, RDFS.label, Literal(f'OWL consistency shapes for {ont_iri or ont_file.name}', lang='en')))
    out.add((shapes_ont, RDFS.comment, Literal(
        f'Generated by tools/owl2shacl.py from {ont_file.name}. Do not edit by hand.', lang='en')))

    def local(iri) -> str:
        s = str(iri)
        return s.rsplit('#', 1)[-1].rsplit('/', 1)[-1]

    def shape(name: str) -> URIRef:
        return URIRef(base + name)

    def max_count(target_pred, target_obj, path, count, name):
        node = shape(name)
        out.add((node, RDF.type, SH.NodeShape))
        out.add((node, target_pred, target_obj))
        prop = BNode()
        out.add((node, SH.property, prop))
        out.add((prop, SH.path, path))
        out.add((prop, SH.maxCount, Literal(int(count))))
        out.add((prop, SH.message, Literal(f'At most {int(count)} value(s) of {local(path)} (OWL cardinality).',
                                           lang='en')))

    for p in sorted(set(ONT.subjects(RDF.type, OWL.ObjectProperty)), key=str):
        if not isinstance(p, URIRef):
            continue
        node = shape(local(p) + '-resource')
        out.add((node, RDF.type, SH.NodeShape))
        out.add((node, SH.targetObjectsOf, p))
        out.add((node, SH.nodeKind, SH.BlankNodeOrIRI))
        out.add((node, SH.message, Literal(f'{local(p)} is an object property: its values are resources, '
                                           f'not literals.', lang='en')))

    for p in sorted(set(ONT.subjects(RDF.type, OWL.DatatypeProperty)), key=str):
        if not isinstance(p, URIRef):
            continue
        node = shape(local(p) + '-literal')
        out.add((node, RDF.type, SH.NodeShape))
        out.add((node, SH.targetObjectsOf, p))
        out.add((node, SH.nodeKind, SH.Literal))
        rng = ONT.value(p, RDFS.range)
        dts = accepted_datatypes(rng) if isinstance(rng, URIRef) else None
        if dts:
            out.add((node, SH['or'], add_list(out, [_dt(out, d) for d in dts])))
            out.add((node, SH.message, Literal(f'{local(p)} is a datatype property with range {local(rng)}: its '
                                               f'values are compatible literals.', lang='en')))
        else:
            out.add((node, SH.message, Literal(f'{local(p)} is a datatype property: its values are literals.',
                                               lang='en')))

    for p in sorted(set(ONT.subjects(RDF.type, OWL.FunctionalProperty)), key=str):
        if isinstance(p, URIRef):
            max_count(SH.targetSubjectsOf, p, p, 1, local(p) + '-functional')

    for cls, restriction in sorted(ONT.subject_objects(RDFS.subClassOf), key=lambda t: str(t[0])):
        if not isinstance(cls, URIRef) or (restriction, RDF.type, OWL.Restriction) not in ONT:
            continue
        prop = ONT.value(restriction, OWL.onProperty)
        count = ONT.value(restriction, OWL.maxCardinality) or ONT.value(restriction, OWL.cardinality)
        if prop is None or count is None:
            continue
        max_count(SH.targetClass, cls, prop, int(count), f'{local(cls)}-{local(prop)}-max')
    return out


def _dt(g: Graph, datatype: URIRef) -> BNode:
    b = BNode()
    g.add((b, SH.datatype, datatype))
    return b


ONT: Graph


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    result = generate(Path(sys.argv[1]))
    result.serialize(sys.argv[2], format='turtle')
    print(f'{sys.argv[2]}: {len(set(result.subjects(RDF.type, SH.NodeShape)))} shapes')
